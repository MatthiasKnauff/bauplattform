-- Wiki (besprochen am 13.11.2026): Erkenntnisse des Büros sammeln, wöchentlich zusammenfassen, nie verlieren.
-- In der Datenbank stehen nur Text und ein kleines Vorschaubild; die Dateien selbst liegen auf der Freigabe „Bauportal“ im Ordner „02 Wiki“.
-- Gesichert wird das Wiki zusätzlich für sich (wiki-….dump und wiki.json in „06 Sicherung“), lesbar auch ohne Bauplattform (Notfallpaket).
CREATE TABLE IF NOT EXISTS wiki_eintrag (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kapitel    TEXT    NOT NULL DEFAULT '',
    titel      TEXT    NOT NULL DEFAULT '',
    text       TEXT    NOT NULL DEFAULT '',
    stichworte TEXT    NOT NULL DEFAULT '',
    quelle     TEXT    NOT NULL DEFAULT '',   -- App oder Stelle, von der der Eintrag kam (z. B. „ava“, „bautagebuch“)
    projekt_id INTEGER,
    status     TEXT    NOT NULL DEFAULT 'neu', -- neu · zusammengefasst · geprueft
    autor      INTEGER,
    created    TEXT    NOT NULL DEFAULT '',
    updated    TEXT    NOT NULL DEFAULT '',
    deleted    TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS wiki_eintrag_kapitel ON wiki_eintrag (kapitel);

CREATE TABLE IF NOT EXISTS wiki_datei (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eintrag  INTEGER NOT NULL REFERENCES wiki_eintrag(id) ON DELETE CASCADE,
    name     TEXT    NOT NULL DEFAULT '',
    pfad     TEXT    NOT NULL DEFAULT '',   -- relativ zu „02 Wiki“ auf der Freigabe Bauportal
    mime     TEXT    NOT NULL DEFAULT '',
    groesse  BIGINT  NOT NULL DEFAULT 0,
    vorschau BYTEA,                         -- nur ein kleines Vorschaubild (JPEG, höchstens 320 px), nie das Dokument
    created  TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS wiki_datei_eintrag ON wiki_datei (eintrag);
