-- Bauplattform: gemeinsam auf einem Plan skizzieren (Ansicht für PDFs in allen Apps).
-- Eine Sitzung hält eine Kopie des Plans (PDF) – so können auch Kollegen ohne Zugriff auf die App/den Ordner mitzeichnen.
CREATE TABLE skizze(
  id TEXT PRIMARY KEY,                         -- zufälliger Schlüssel (auch im Link #skizze=…)
  name TEXT NOT NULL DEFAULT '',               -- Dateiname des Plans
  owner INTEGER, owner_name TEXT NOT NULL DEFAULT '',
  datei BYTEA,                                 -- der Plan (PDF)
  seq INTEGER NOT NULL DEFAULT 0,              -- zählt jede Änderung (Striche, Löschen) – für das Nachladen
  teilnehmer TEXT NOT NULL DEFAULT '[]',       -- JSON: [uid, …] (eingeladen oder beigetreten)
  created TEXT NOT NULL DEFAULT '', updated TEXT NOT NULL DEFAULT '');
CREATE TABLE skizze_strich(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  skizze_id TEXT NOT NULL REFERENCES skizze(id) ON DELETE CASCADE,
  seq INTEGER NOT NULL DEFAULT 0, uid INTEGER, name TEXT NOT NULL DEFAULT '',
  data TEXT NOT NULL DEFAULT '{}',             -- JSON: {seite, art: stift|marker|text|pfeil, farbe, breite, pts:[[x,y]…] (0…1), text}
  geloescht INTEGER NOT NULL DEFAULT 0, created TEXT NOT NULL DEFAULT '');
CREATE INDEX skizze_strich_seq ON skizze_strich(skizze_id, seq);
CREATE TABLE skizze_cursor(                    -- wo die anderen gerade zeigen (Laserpointer)
  skizze_id TEXT NOT NULL REFERENCES skizze(id) ON DELETE CASCADE, uid INTEGER NOT NULL,
  name TEXT NOT NULL DEFAULT '', farbe TEXT NOT NULL DEFAULT '', seite INTEGER NOT NULL DEFAULT 0,
  x DOUBLE PRECISION, y DOUBLE PRECISION, t BIGINT NOT NULL DEFAULT 0, PRIMARY KEY(skizze_id, uid));
CREATE TABLE skizze_einladung(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  skizze_id TEXT NOT NULL REFERENCES skizze(id) ON DELETE CASCADE,
  an INTEGER NOT NULL, von TEXT NOT NULL DEFAULT '', created TEXT NOT NULL DEFAULT '', erledigt INTEGER NOT NULL DEFAULT 0);
CREATE INDEX skizze_einladung_an ON skizze_einladung(an, erledigt);
