-- Honorar überschlagen → ablegen (besprochen am 14.11.2026, Mock „Überschlag ablegen“): ein Ergebnis des Rechners für später merken,
-- ohne Projekt; nur die Verwaltung (Geschäftsführung) sieht die abgelegten. Übernommen wird es als Honorarauftrag (Stand Angebot) –
-- dann wandert der Überschlag in den Papierkorb (Rückgängig holt ihn zurück).
CREATE TABLE IF NOT EXISTS honorar_ueberschlag (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wofuer   TEXT    NOT NULL DEFAULT '',
    kosten   REAL    NOT NULL DEFAULT 0,
    zone     INTEGER NOT NULL DEFAULT 3,
    satz     REAL    NOT NULL DEFAULT 0,
    umbau    REAL    NOT NULL DEFAULT 0,
    nk       REAL    NOT NULL DEFAULT 5,
    netto    REAL    NOT NULL DEFAULT 0,
    von      TEXT    NOT NULL DEFAULT '',
    geraet   TEXT    NOT NULL DEFAULT '',
    erstellt TEXT    NOT NULL DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS')
);
-- Live: Ablegen am Handy zeigt sich am Rechner gleich (Frage, Zahl in der Navigation)
DROP TRIGGER IF EXISTS bp_live ON honorar_ueberschlag;
CREATE TRIGGER bp_live AFTER INSERT OR UPDATE OR DELETE ON honorar_ueberschlag FOR EACH ROW EXECUTE FUNCTION bp_aenderung_merken();
