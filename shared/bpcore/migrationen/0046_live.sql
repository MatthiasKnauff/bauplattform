-- Live-Aktualisierung: jede Änderung an den wichtigen Tabellen hinterlässt eine kleine Zeile (welche Tabelle, welches Projekt, wer).
-- Die Seiten fragen alle paar Sekunden „was ist seit Nr. x passiert?“ (bpcore/live.py) und laden ihre Daten neu, wenn es sie betrifft.
-- Wer geändert hat, setzt db.tx je Transaktion (set_config('bp.user', …)); eigene Änderungen lösen bei einem selbst nichts aus.
CREATE TABLE IF NOT EXISTS bp_aenderung (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabelle    TEXT    NOT NULL,
    project_id INTEGER,
    von        INTEGER,
    zeit       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_bp_aenderung_zeit ON bp_aenderung(zeit);

CREATE OR REPLACE FUNCTION bp_aenderung_merken() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    j   jsonb := to_jsonb(COALESCE(NEW, OLD));
    pid INTEGER;
    u   TEXT := current_setting('bp.user', true);
BEGIN
    IF TG_TABLE_NAME = 'projects' THEN
        pid := (j->>'id')::int;
    ELSIF j ? 'project_id' THEN
        pid := NULLIF(j->>'project_id', '')::int;
    ELSIF j ? 'report_id' THEN
        SELECT project_id INTO pid FROM reports WHERE id = NULLIF(j->>'report_id', '')::int;
    END IF;
    INSERT INTO bp_aenderung(tabelle, project_id, von) VALUES (TG_TABLE_NAME, pid, NULLIF(u, '')::int);
    RETURN NULL;
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;   -- die Live-Meldung darf eine Änderung nie verhindern
END $$;

DO $$
DECLARE t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['projects','reports','items','images','todo','erinnerungen','contacts','honorar_auftrag','honorar_nk','bauantrag',
                             'kom_vorgang','planversand','ava_lv','ava_rechnung','ava_angebot','ava_aufmass','bk_projects','zeit_eintrag','zeit_antrag'] LOOP
        IF to_regclass(t) IS NOT NULL THEN
            EXECUTE format('DROP TRIGGER IF EXISTS bp_live ON %I', t);
            EXECUTE format('CREATE TRIGGER bp_live AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION bp_aenderung_merken()', t);
        END IF;
    END LOOP;
END $$;
