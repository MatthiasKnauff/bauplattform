-- Honorar: Architektenvertrag und Ablage im Projektordner.
-- honorar_vertrag: gespeicherte Fassungen des Vertrags (PDF), v. a. die unterschriebene (aus der gemeinsamen PDF-Vorschau, ✍ Unterschreiben).
-- ablage: Pfad im Projektordner, wenn dort abgelegt (Rechnung beim Stellen, Vertrag beim Speichern).
ALTER TABLE honorar_rechnung ADD COLUMN IF NOT EXISTS ablage TEXT NOT NULL DEFAULT '';
CREATE TABLE IF NOT EXISTS honorar_vertrag (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auftrag_id     INTEGER NOT NULL REFERENCES honorar_auftrag(id) ON DELETE CASCADE,
    name           TEXT    NOT NULL DEFAULT '',
    pdf            BYTEA,
    unterschrieben BOOLEAN NOT NULL DEFAULT FALSE,
    ablage         TEXT    NOT NULL DEFAULT '',
    erstellt       TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    von            TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_honorar_vertrag_auftrag ON honorar_vertrag(auftrag_id);
