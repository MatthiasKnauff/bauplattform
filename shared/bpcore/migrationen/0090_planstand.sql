-- Planstände des Gebäudemodells (GO 16.11.2026, Entwurf „Gebäudemodell als Mitte“; Programm: bpcore/planstand.py)
-- Jeder eingelesene Plan (IFC, DXF, PDF) wird ein Planstand – wie die Versionen der anderen Apps: Name, „gilt“ (im Modell steht
-- quelle.planstand), archivieren, löschen. Gespeichert wird nur, was ausgelesen wurde (Bauteilliste mit Antworten, Räume) –
-- nie die Datei selbst; die liegt in „Pläne & Dateien“ (pfad) oder kam vom Gerät. entwurf = 1: eingelesen, Abgleich noch nicht übernommen.
CREATE TABLE IF NOT EXISTS pm_planstand (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  INTEGER NOT NULL,
    name        TEXT    NOT NULL DEFAULT '',
    datei       TEXT    NOT NULL DEFAULT '',
    pfad        TEXT    NOT NULL DEFAULT '',
    quelle      TEXT    NOT NULL DEFAULT '',
    art         TEXT    NOT NULL DEFAULT '',
    wer         TEXT    NOT NULL DEFAULT '',
    erstellt    TEXT    NOT NULL DEFAULT '',
    entwurf     INTEGER NOT NULL DEFAULT 0,
    archiviert  INTEGER NOT NULL DEFAULT 0,
    daten       TEXT    NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS pm_planstand_projekt ON pm_planstand(project_id);
