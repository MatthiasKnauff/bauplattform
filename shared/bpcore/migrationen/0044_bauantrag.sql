-- Bauantrag: je Projekt beliebig viele Anträge (Baugenehmigung, Vorbescheid, Abweichung …).
-- daten: JSON {feld: wert} – nur was von Hand eingetragen oder geändert wurde; alles andere kommt jeweils frisch aus den Quellen
-- (Projektdaten, Adressen, Baukosten, Büro, Mein Konto). bauvorlagen: JSON {schlüssel: {status, datei, notiz}}.
CREATE TABLE IF NOT EXISTS bauantrag (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name        TEXT    NOT NULL DEFAULT '',
    verfahren   TEXT    NOT NULL DEFAULT 'baugenehmigung',
    land        TEXT    NOT NULL DEFAULT 'NW',
    status      TEXT    NOT NULL DEFAULT 'entwurf',
    daten       TEXT    NOT NULL DEFAULT '{}',
    bauvorlagen TEXT    NOT NULL DEFAULT '{}',
    erstellt    TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    geaendert   TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    von         TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_bauantrag_projekt ON bauantrag(project_id);
