-- Bauplattform AVA: Positionskatalog (z. B. sirAdos) – in der App hochgeladen, NICHT im Repository (Lizenz).
-- Eine Zeile je Gewerk, Titel oder Position in Katalog-Reihenfolge (nr). Wird beim Einlesen komplett ersetzt.
CREATE TABLE ava_katalog(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nr INTEGER NOT NULL,                        -- Reihenfolge im Katalog
  gewerk TEXT NOT NULL DEFAULT '',            -- OZ des Gewerks, z. B. „012“
  typ TEXT NOT NULL,                          -- gewerk | titel | pos
  ebene INTEGER NOT NULL DEFAULT 0,
  oz TEXT NOT NULL DEFAULT '',
  kurz TEXT NOT NULL DEFAULT '',
  lang TEXT NOT NULL DEFAULT '',
  art TEXT NOT NULL DEFAULT 'N',              -- N = Normalposition, T = Hinweistext
  einheit TEXT NOT NULL DEFAULT '',
  kg TEXT NOT NULL DEFAULT '',
  ep_von DOUBLE PRECISION, ep DOUBLE PRECISION, ep_bis DOUBLE PRECISION);
CREATE INDEX ava_katalog_gewerk ON ava_katalog(gewerk, nr);
