-- Bauplattform: Chat in der Kopfleiste aller Apps – je App ein fester (angepinnter) Raum und ein Gesamtchat für alle.
-- raum = 'gesamt' oder der App-Schlüssel (bautagebuch, gantt, adressen, baukosten, aufgaben, plaene, ava, kommunikation, baudaten, admin).
CREATE TABLE chat_nachricht(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raum TEXT NOT NULL,
  uid INTEGER, name TEXT NOT NULL DEFAULT '',
  text TEXT NOT NULL DEFAULT '',
  projekt TEXT NOT NULL DEFAULT '',             -- Projekt, in dem der Absender gerade war (nur zur Anzeige)
  created TEXT NOT NULL DEFAULT '',
  geloescht INTEGER NOT NULL DEFAULT 0);
CREATE INDEX chat_nachricht_raum ON chat_nachricht(raum, id);
CREATE TABLE chat_gelesen(                     -- bis zu welcher Nachricht jeder Benutzer einen Raum gelesen hat (für die Zahl am Knopf)
  uid INTEGER NOT NULL, raum TEXT NOT NULL, bis INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(uid, raum));
