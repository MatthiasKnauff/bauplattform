-- Abwesenheiten zurücknehmen und löschen (17.11.2026): Recht „urlaub.aendern“ (Abwesenheiten anderer ändern), ab Werk Geschäftsführung,
-- Büroleitung und Assistenz. zeit_antrag.zurueck: zurückgegebene Tage eines genehmigten Antrags (JSON-Liste) – „teilweise zurückgenommen“;
-- ganz zurückgenommen = status 'zurueckgenommen'.
ALTER TABLE zeit_antrag ADD COLUMN IF NOT EXISTS zurueck TEXT NOT NULL DEFAULT '[]';
UPDATE rollen SET rechte = (COALESCE(NULLIF(rechte, ''), '[]')::jsonb || '["urlaub.aendern"]'::jsonb)::text
    WHERE key IN ('gf', 'bueroleitung', 'assistenz') AND rechte NOT LIKE '%"urlaub.aendern"%';
UPDATE users u SET rechte = (COALESCE(NULLIF(u.rechte, ''), '[]')::jsonb || '["urlaub.aendern"]'::jsonb)::text
    WHERE u.rolle IN ('gf', 'bueroleitung', 'assistenz') AND COALESCE(u.rechte, '') NOT LIKE '%"urlaub.aendern"%'
      AND COALESCE(u.rechte_minus, '') NOT LIKE '%"urlaub.aendern"%';
-- Benachrichtigungen über zurückgenommene oder gelöschte Abwesenheiten (nur wen der Dialog angehakt hat) – Startseite „Neu für dich“.
CREATE TABLE IF NOT EXISTS zeit_abw_meldung (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    ts      TEXT    NOT NULL,
    titel   TEXT    NOT NULL DEFAULT '',
    text    TEXT    NOT NULL DEFAULT '',
    von     TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_zeit_abw_meldung ON zeit_abw_meldung(user_id, ts);
