-- Bauplattform: Papierkorb für alle Apps (statt endgültig zu löschen). Siehe shared/bpcore/papierkorb.py.
CREATE TABLE bp_papierkorb(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  art TEXT NOT NULL DEFAULT '',               -- z. B. „Bauzeitenplan“, „Kostenermittlung“, „Bautagebuch-Projekt“
  titel TEXT NOT NULL DEFAULT '',
  projekt TEXT NOT NULL DEFAULT '',
  app TEXT NOT NULL DEFAULT '',               -- App, aus der gelöscht wurde (Link nach dem Wiederherstellen, Dateien)
  tabelle TEXT NOT NULL DEFAULT '', schluessel TEXT NOT NULL DEFAULT '',
  data TEXT NOT NULL DEFAULT '{}',            -- JSON {teile:[{t, rows}], relink:[…]}
  dateien TEXT NOT NULL DEFAULT '[]',         -- Dateien auf dem Datenträger, die erst beim endgültigen Löschen weg dürfen
  groesse INTEGER NOT NULL DEFAULT 0,
  geloescht TEXT NOT NULL DEFAULT '', von TEXT NOT NULL DEFAULT '');
CREATE INDEX bp_papierkorb_zeit ON bp_papierkorb(geloescht);
