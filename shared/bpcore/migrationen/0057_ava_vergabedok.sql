-- Ausschreibung: Unterlagen der Vergabe je LV – Angebotsbesprechung (Protokoll je Bieter) und Bauvertrag / Auftragsschreiben.
-- art: besprechung | vertrag | schreiben; status: entwurf | abgeschlossen (in Angebot/Auftrag übernommen) | unterschrieben (PDF hinterlegt).
-- data: JSON mit allen Feldern (Kopf, Bieter, Angebot, Termine, Grundlagen, Sonstiges bzw. Vertragsangaben); pdf: unterschriebene Fassung.
CREATE TABLE IF NOT EXISTS ava_vergabedok (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lv_id       INTEGER NOT NULL REFERENCES ava_lv(id) ON DELETE CASCADE,
    angebot_id  INTEGER,
    art         TEXT    NOT NULL DEFAULT 'besprechung',
    status      TEXT    NOT NULL DEFAULT 'entwurf',
    data        TEXT    NOT NULL DEFAULT '{}',
    pdf         BYTEA,
    pdf_name    TEXT    NOT NULL DEFAULT '',
    ablage      TEXT    NOT NULL DEFAULT '',
    erstellt    TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    geaendert   TEXT    NOT NULL DEFAULT '',
    von         TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_ava_vergabedok_lv ON ava_vergabedok(lv_id);

DO $$
BEGIN
    IF to_regprocedure('bp_aenderung_merken()') IS NOT NULL THEN
        DROP TRIGGER IF EXISTS bp_live ON ava_vergabedok;
        CREATE TRIGGER bp_live AFTER INSERT OR UPDATE OR DELETE ON ava_vergabedok FOR EACH ROW EXECUTE FUNCTION bp_aenderung_merken();
    END IF;
END $$;
