-- Amtliche Bauantragsformulare je Bundesland (App „Bauantrag“, bpcore/bauantrag_formulare.py).
-- NRW: Anlagen zur VV BauPrüfVO von recht.nrw.de, täglich geprüft, die PDFs liegen hier (daten). Andere Länder: auf Abruf, nur Liste mit Link.
-- status: aktuell | neu (Anlage kam hinzu) | geaendert (neue Fassung) | entfallen – „neu“/„geaendert“ erscheinen als To-do, bis jemand „gesehen“ drückt.
CREATE TABLE IF NOT EXISTS bauantrag_formular (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    land      TEXT    NOT NULL,
    schluessel TEXT   NOT NULL,
    nr        TEXT    NOT NULL DEFAULT '',
    titel     TEXT    NOT NULL DEFAULT '',
    url       TEXT    NOT NULL DEFAULT '',
    sha256    TEXT    NOT NULL DEFAULT '',
    groesse   INTEGER NOT NULL DEFAULT 0,
    daten     BYTEA,
    fassung   TEXT    NOT NULL DEFAULT '',
    status    TEXT    NOT NULL DEFAULT 'aktuell',
    gefunden  TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    geaendert TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    UNIQUE (land, schluessel)
);
