-- Honorar: Fachplaner über unser Büro (Fremdleistungen) je Honorarauftrag und ihre Rechnungen an uns.
-- beauftragt: buero (über uns, wird weiterberechnet) | bauherr (vom Bauherrn direkt – nur zur Koordination).
-- weiter: durch (durchgereicht) | zuschlag (zuschlag_p % auf den Nettobetrag) | pauschal (pauschal_betrag statt der Rechnungen).
CREATE TABLE IF NOT EXISTS honorar_fremd (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auftrag_id      INTEGER NOT NULL REFERENCES honorar_auftrag(id) ON DELETE CASCADE,
    contact_id      INTEGER,
    firma           TEXT    NOT NULL DEFAULT '',
    leistung        TEXT    NOT NULL DEFAULT '',
    beauftragt      TEXT    NOT NULL DEFAULT 'buero',
    vertrag         TEXT    NOT NULL DEFAULT '',
    auftrag_netto   DOUBLE PRECISION,
    weiter          TEXT    NOT NULL DEFAULT 'zuschlag',
    zuschlag_p      DOUBLE PRECISION NOT NULL DEFAULT 0,
    notiz           TEXT    NOT NULL DEFAULT '',
    erstellt        TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    von             TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_honorar_fremd_auftrag ON honorar_fremd(auftrag_id);

-- Rechnungen der Fachplaner an uns: eingang → geprueft → freigegeben → bezahlt (oder abgelehnt).
-- weiter: in unsere nächste Rechnung übernehmen; re_id: in welcher unserer Rechnungen weiterberechnet (beim Stellen gesetzt).
CREATE TABLE IF NOT EXISTS honorar_fremd_re (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fremd_id    INTEGER NOT NULL REFERENCES honorar_fremd(id) ON DELETE CASCADE,
    nr          TEXT    NOT NULL DEFAULT '',
    datum       TEXT    NOT NULL DEFAULT '',
    netto       DOUBLE PRECISION NOT NULL DEFAULT 0,
    status      TEXT    NOT NULL DEFAULT 'eingang',
    weiter      BOOLEAN NOT NULL DEFAULT TRUE,
    re_id       INTEGER REFERENCES honorar_rechnung(id) ON DELETE SET NULL,
    datei       BYTEA,
    dateiname   TEXT    NOT NULL DEFAULT '',
    notiz       TEXT    NOT NULL DEFAULT '',
    erstellt    TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    von         TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_honorar_fremd_re_fremd ON honorar_fremd_re(fremd_id);

DO $$
BEGIN
    IF to_regprocedure('bp_aenderung_merken()') IS NOT NULL THEN
        DROP TRIGGER IF EXISTS bp_live ON honorar_fremd;
        CREATE TRIGGER bp_live AFTER INSERT OR UPDATE OR DELETE ON honorar_fremd FOR EACH ROW EXECUTE FUNCTION bp_aenderung_merken();
        DROP TRIGGER IF EXISTS bp_live ON honorar_fremd_re;
        CREATE TRIGGER bp_live AFTER INSERT OR UPDATE OR DELETE ON honorar_fremd_re FOR EACH ROW EXECUTE FUNCTION bp_aenderung_merken();
    END IF;
END $$;
