-- Bauplattform: zentrale Erinnerungen (App „Mängel & Erinnerungen“).
-- quelle 'plan' = aus einem Bauzeitenplan erzeugt (Firma kommt zur Baustelle), 'eigen' = von Hand angelegt.
-- Erinnerungen aus dem Bautagebuch (Mängel, Weisungen, Zu erledigen) bleiben in der Tabelle items.
CREATE TABLE erinnerungen(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quelle TEXT NOT NULL DEFAULT 'eigen',
  schluessel TEXT UNIQUE,
  project_id INTEGER REFERENCES projects(id) ON DELETE SET NULL,
  gantt_id TEXT,
  titel TEXT NOT NULL DEFAULT '',
  text TEXT NOT NULL DEFAULT '',
  termin TEXT NOT NULL DEFAULT '',          -- Datum der Erinnerung (JJJJ-MM-TT)
  uhrzeit TEXT NOT NULL DEFAULT '08:00',
  ereignis TEXT NOT NULL DEFAULT '',        -- worum es geht, z. B. Beginn der Arbeiten (JJJJ-MM-TT)
  empfaenger TEXT NOT NULL DEFAULT '[]',    -- Benutzer-IDs (JSON)
  status TEXT NOT NULL DEFAULT 'offen',     -- offen | erledigt | entfallen
  gesendet TEXT NOT NULL DEFAULT '',
  manuell INTEGER NOT NULL DEFAULT 0,       -- Termin von Hand verschoben: der Abgleich mit dem Plan lässt ihn stehen
  daten TEXT NOT NULL DEFAULT '{}',
  erstellt TEXT NOT NULL DEFAULT '', erstellt_von TEXT NOT NULL DEFAULT '',
  geaendert TEXT NOT NULL DEFAULT '', geaendert_von TEXT NOT NULL DEFAULT '');
CREATE INDEX idx_erinnerungen_termin ON erinnerungen(termin);
CREATE TABLE bp_store(key TEXT PRIMARY KEY, data TEXT NOT NULL DEFAULT '{}', updated TEXT NOT NULL DEFAULT '', updated_by TEXT NOT NULL DEFAULT '');
