-- Bauplattform: Positionsdatenbank (Baupositionen mit Kurz-/Langtext, Einheit, DIN-276-Kostengruppe und Preisspanne)
-- für Kostenschätzung (Baukosten) und Leistungsverzeichnisse (Ausschreibung/Vergabe).
-- Gliederung nach Leistungsbereichen (Nummern angelehnt an das StLB-Bau) → Gruppen → Positionen.
-- Mehrere Kataloge nebeneinander (pdb_katalog): 'gk3' = eigene Positionsdatenbank (Migration 0024 ff., quelle = 'katalog'),
-- importierte Kataloge (z. B. Sirados aus GAEB, quelle = 'import') und 'eigen' (im Büro angelegt, quelle = 'eigen').
-- Eigene und importierte Positionen werden von späteren Katalog-Updates nie überschrieben.

CREATE TABLE pdb_katalog(
  key TEXT PRIMARY KEY,                       -- 'gk3', 'eigen', 'sirados' …
  name TEXT NOT NULL DEFAULT '',
  art TEXT NOT NULL DEFAULT 'import',         -- katalog | eigen | import
  lizenz TEXT NOT NULL DEFAULT '',            -- Hinweis zur Nutzung (z. B. Lizenz des Anbieters)
  preisstand TEXT NOT NULL DEFAULT '',
  index_basis REAL,                           -- Baupreisindex zum Preisstand (für die Fortschreibung)
  sort INTEGER NOT NULL DEFAULT 0,
  created TEXT, updated TEXT, updated_by TEXT NOT NULL DEFAULT '');
