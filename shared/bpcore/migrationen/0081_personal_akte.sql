        DROP TRIGGER IF EXISTS bp_live ON personal_frist;
        CREATE TRIGGER bp_live AFTER INSERT OR UPDATE OR DELETE ON personal_frist FOR EACH ROW EXECUTE FUNCTION bp_aenderung_merken();
    END IF;
END $$;
