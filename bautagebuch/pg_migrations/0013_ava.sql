-- Bauplattform: Ausschreibung & Abrechnung (AVA) – Leistungsverzeichnisse, Angebote, Aufmaß, Rechnungen.
-- Ein LV gehört zu einem Projekt des Bautagebuchs (meist eins je Gewerk / Vergabeeinheit).
CREATE TABLE ava_lv(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER REFERENCES projects(id) ON DELETE CASCADE,
  bk_id INTEGER,                              -- Kostenermittlung (Baukosten), aus der übernommen wurde
  nr TEXT NOT NULL DEFAULT '',                -- LV-Nummer, z. B. „03“
  name TEXT NOT NULL DEFAULT '',              -- z. B. „Rohbauarbeiten“
  gewerk TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'entwurf',     -- entwurf | versendet | vergeben | abgerechnet
  data TEXT NOT NULL DEFAULT '{}',            -- JSON {items:[{id, typ:'titel'|'pos', oz, kurz, lang, menge, einheit, art, kg, ep_s, nt, nt_status}], vorbem}
  vergabe TEXT NOT NULL DEFAULT '{}',         -- JSON {angebot_id, contact_id, bieter, datum, nachlass, skonto, einbehalt}
  archived INTEGER NOT NULL DEFAULT 0,
  rev INTEGER NOT NULL DEFAULT 0,
  created TEXT, updated TEXT, updated_by TEXT NOT NULL DEFAULT '');
CREATE INDEX ava_lv_projekt ON ava_lv(project_id, id);

CREATE TABLE ava_angebot(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lv_id INTEGER NOT NULL REFERENCES ava_lv(id) ON DELETE CASCADE,
  contact_id INTEGER REFERENCES contacts(id) ON DELETE SET NULL,
  bieter TEXT NOT NULL DEFAULT '',
  eingang TEXT NOT NULL DEFAULT '',
  preise TEXT NOT NULL DEFAULT '{}',          -- JSON {Positions-ID: Einheitspreis}
  nachlass REAL NOT NULL DEFAULT 0,           -- Prozent
  skonto REAL NOT NULL DEFAULT 0,
  notiz TEXT NOT NULL DEFAULT '',
  quelle TEXT NOT NULL DEFAULT 'hand',        -- hand | gaeb
  created TEXT, updated TEXT);
CREATE INDEX ava_angebot_lv ON ava_angebot(lv_id, id);

CREATE TABLE ava_aufmass(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lv_id INTEGER NOT NULL REFERENCES ava_lv(id) ON DELETE CASCADE,
  pos_id TEXT NOT NULL,
  datum TEXT NOT NULL DEFAULT '',
  ort TEXT NOT NULL DEFAULT '',               -- z. B. „EG Bad“, „Achse A–C“
  formel TEXT NOT NULL DEFAULT '',
  menge REAL NOT NULL DEFAULT 0,
  quelle TEXT NOT NULL DEFAULT '',            -- hand | raum:<id> | bericht:<id>
  created TEXT, user_name TEXT NOT NULL DEFAULT '');
CREATE INDEX ava_aufmass_lv ON ava_aufmass(lv_id, pos_id, id);

CREATE TABLE ava_rechnung(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lv_id INTEGER NOT NULL REFERENCES ava_lv(id) ON DELETE CASCADE,
  nr INTEGER NOT NULL DEFAULT 1,
  art TEXT NOT NULL DEFAULT 'abschlag',       -- abschlag | schluss
  datum TEXT NOT NULL DEFAULT '',             -- Rechnungsdatum
  eingang TEXT NOT NULL DEFAULT '',
  re_nr TEXT NOT NULL DEFAULT '',             -- Rechnungsnummer der Firma
  gefordert REAL NOT NULL DEFAULT 0,          -- netto, kumuliert laut Firma
  data TEXT NOT NULL DEFAULT '{}',            -- JSON Prüfung: {stand:{pos_id: menge}, abzuege:[…], einbehalt, …}
  status TEXT NOT NULL DEFAULT 'offen',       -- offen | geprueft
  notiz TEXT NOT NULL DEFAULT '',
  created TEXT, updated TEXT, updated_by TEXT NOT NULL DEFAULT '');
CREATE INDEX ava_rechnung_lv ON ava_rechnung(lv_id, nr);
