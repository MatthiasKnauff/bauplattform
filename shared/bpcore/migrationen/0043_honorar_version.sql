-- Honorar: Versionen wie in Baukosten/AVA. Eine Version ist ein gespeicherter Stand – je Auftrag (auftrag_id gesetzt, daten = ein Auftrag)
-- oder je Projekt (auftrag_id NULL, daten = alle Aufträge des Projekts). Welche Art gerade gilt, steht in bp_store „honorar:modus:<projekt>“
-- und lässt sich jederzeit umstellen; die Versionen beider Arten bleiben erhalten. gilt = die beauftragte/gültige Version.
CREATE TABLE IF NOT EXISTS honorar_version (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    auftrag_id  INTEGER REFERENCES honorar_auftrag(id) ON DELETE CASCADE,
    name        TEXT    NOT NULL DEFAULT '',
    gilt        BOOLEAN NOT NULL DEFAULT FALSE,
    daten       TEXT    NOT NULL DEFAULT '[]',
    erstellt    TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    von         TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_honorar_version_projekt ON honorar_version(project_id);
