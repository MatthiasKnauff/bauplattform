-- Honorar (App „Honorar“, nur Verwaltung): Aufträge je Projekt nach HOAI, nach Aufwand oder pauschal – Berechnung in bpcore/honorar.py.
-- status: angebot, beauftragt, abgeschlossen; lph/nk als JSON (Leistungsphasen mit Prozent, Nebenkosten pauschal/nach Aufwand)
CREATE TABLE IF NOT EXISTS honorar_auftrag (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name        TEXT    NOT NULL DEFAULT '',
    art         TEXT    NOT NULL DEFAULT 'hoai',
    status      TEXT    NOT NULL DEFAULT 'angebot',
    kosten      REAL    NOT NULL DEFAULT 0,
    kosten_info TEXT    NOT NULL DEFAULT '',
    zone        INTEGER NOT NULL DEFAULT 3,
    satz        REAL    NOT NULL DEFAULT 0,
    umbau       REAL    NOT NULL DEFAULT 0,
    lph         TEXT    NOT NULL DEFAULT '{}',
    nk          TEXT    NOT NULL DEFAULT '{}',
    einheit     INTEGER NOT NULL DEFAULT 15,
    satz_h      REAL,
    pauschal    REAL,
    auftraggeber TEXT   NOT NULL DEFAULT '',
    notiz       TEXT    NOT NULL DEFAULT '',
    datum       TEXT    NOT NULL DEFAULT '',
    erstellt    TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    geaendert   TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    von         TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_honorar_auftrag_projekt ON honorar_auftrag(project_id);

-- Nebenkosten nach Aufwand (§ 14): Plotaufträge, Fahrten, Sonstiges
CREATE TABLE IF NOT EXISTS honorar_nk (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auftrag_id INTEGER NOT NULL REFERENCES honorar_auftrag(id) ON DELETE CASCADE,
    datum      TEXT    NOT NULL DEFAULT '',
    art        TEXT    NOT NULL DEFAULT 'sonst',
    text       TEXT    NOT NULL DEFAULT '',
    betrag     REAL    NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_honorar_nk_auftrag ON honorar_nk(auftrag_id);
