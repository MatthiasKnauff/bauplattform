CREATE TABLE sync_jobs(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL, local TEXT NOT NULL, remote TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending', tries INTEGER NOT NULL DEFAULT 0, retry_at BIGINT NOT NULL DEFAULT 0,
  error TEXT NOT NULL DEFAULT '', extra TEXT NOT NULL DEFAULT '{}',
  created TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  updated TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'));
CREATE INDEX idx_sync_status ON sync_jobs(status, retry_at);

CREATE TABLE report_versions(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id INTEGER NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  created TEXT NOT NULL, user_name TEXT NOT NULL DEFAULT '', reason TEXT NOT NULL DEFAULT 'auto',
  pdf_name TEXT NOT NULL DEFAULT '', hash TEXT NOT NULL DEFAULT '', data TEXT NOT NULL DEFAULT '{}');
CREATE INDEX idx_rv_report ON report_versions(report_id, id);

CREATE TABLE audit_log(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts TEXT NOT NULL, user_name TEXT NOT NULL DEFAULT '', cat TEXT NOT NULL DEFAULT 'inhalt',
  action TEXT NOT NULL, detail TEXT NOT NULL DEFAULT '', project_id INTEGER,
  project TEXT NOT NULL DEFAULT '', report TEXT NOT NULL DEFAULT '');
CREATE INDEX idx_audit_ts ON audit_log(id DESC);
CREATE INDEX idx_audit_proj ON audit_log(project_id, id DESC);
