-- Wärmeschutz: Bauteilnachweise je Projekt (GModG Anlage 7, DIN EN ISO 6946, DIN 4108-2/-3) und der Bauteilkatalog des Büros.
-- ws_nachweis.status: grundlagen | bauteile | pruefung | nachweis | eingereicht (Ablaufleiste).
-- ws_nachweis.data: JSON {grundlagen: {...}, bauteile: [{id, kurz, name, typ, massnahme, zone, flaeche, schichten: [{m, d, lam?, mu?, m2?, breite?, abstand?}]}]}
-- ws_katalog: Aufbauten zum Wiederverwenden (gleiches Schichtformat).
CREATE TABLE IF NOT EXISTS ws_nachweis (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name        TEXT    NOT NULL DEFAULT '',
    status      TEXT    NOT NULL DEFAULT 'grundlagen',
    data        TEXT    NOT NULL DEFAULT '{}',
    erstellt    TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    geaendert   TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    von         TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_ws_nachweis_projekt ON ws_nachweis(project_id);

CREATE TABLE IF NOT EXISTS ws_katalog (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT    NOT NULL DEFAULT '',
    typ         TEXT    NOT NULL DEFAULT 'wand',
    schichten   TEXT    NOT NULL DEFAULT '[]',
    erstellt    TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    von         TEXT    NOT NULL DEFAULT ''
);

DO $$
BEGIN
    IF to_regprocedure('bp_aenderung_merken()') IS NOT NULL THEN
        DROP TRIGGER IF EXISTS bp_live ON ws_nachweis;
        CREATE TRIGGER bp_live AFTER INSERT OR UPDATE OR DELETE ON ws_nachweis FOR EACH ROW EXECUTE FUNCTION bp_aenderung_merken();
    END IF;
END $$;
