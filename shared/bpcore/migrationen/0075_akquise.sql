-- App „Akquise“ (besprochen am 14.11.2026, Entwurf „Akquise-App“): Akquisen sind keine Projekte – nur Daten hier, die Dateien im
-- Projektpfad unter „Akquise/<Ordner>“ (nie Dokumente in der Datenbank). Umwandeln legt ein echtes Projekt an (project_id), der Ordner
-- wandert in den Projektpfad. Sehen und bearbeiten: Recht „akquise“ – ab Werk Geschäftsführung, weitere Rollen in der Verwaltung.
CREATE TABLE IF NOT EXISTS akquise (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT    NOT NULL DEFAULT '',
    ordner        TEXT    NOT NULL DEFAULT '',
    bauherr       TEXT    NOT NULL DEFAULT '',
    ansprech      TEXT    NOT NULL DEFAULT '',
    telefon       TEXT    NOT NULL DEFAULT '',
    email         TEXT    NOT NULL DEFAULT '',
    adresse       TEXT    NOT NULL DEFAULT '',
    stand         TEXT    NOT NULL DEFAULT 'anfrage',
    wiedervorlage TEXT    NOT NULL DEFAULT '',
    notiz         TEXT    NOT NULL DEFAULT '',
    archiviert    INTEGER NOT NULL DEFAULT 0,
    project_id    INTEGER REFERENCES projects(id) ON DELETE SET NULL,
    von           TEXT    NOT NULL DEFAULT '',
    erstellt      TEXT    NOT NULL DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS'),
    geaendert     TEXT    NOT NULL DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS')
);
