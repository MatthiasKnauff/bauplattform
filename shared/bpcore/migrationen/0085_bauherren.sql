-- Das Portal läuft auf einem eigenen Server und erreicht das Büro nie: der Kern schiebt hinaus und holt ab.
-- bh_freigabe  was für Bauherr:innen freigegeben ist (ein Paket je schluessel, ersetzt beim neuen Freigeben); gesendet = wann zuletzt hinausgeschickt
-- bh_konto     eingeladene Bauherr:innen je Projekt (aktiv 0 = gesperrt; das Portal meldet sie sofort ab)
-- bh_eingang   was aus dem Portal kam (Nachrichten …) – wird ein To-do, bis jemand es erledigt
CREATE TABLE IF NOT EXISTS bh_freigabe (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schluessel  TEXT    NOT NULL UNIQUE,
    project_id  INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    art         TEXT    NOT NULL DEFAULT '',
    titel       TEXT    NOT NULL DEFAULT '',
    stand       TEXT    NOT NULL DEFAULT '',
    daten       TEXT    NOT NULL DEFAULT '{}',
    von         TEXT    NOT NULL DEFAULT '',
    created     TEXT    NOT NULL DEFAULT '',
    updated     TEXT    NOT NULL DEFAULT '',
    gesendet    TEXT    NOT NULL DEFAULT '',
    geloescht   TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS bh_freigabe_projekt ON bh_freigabe (project_id);
CREATE TABLE IF NOT EXISTS bh_konto (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    email       TEXT    NOT NULL,
    name        TEXT    NOT NULL DEFAULT '',
    aktiv       INTEGER NOT NULL DEFAULT 1,
    created     TEXT    NOT NULL DEFAULT '',
    updated     TEXT    NOT NULL DEFAULT '',
    gesendet    TEXT    NOT NULL DEFAULT '',
    UNIQUE (project_id, email)
);
CREATE TABLE IF NOT EXISTS bh_eingang (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fern_id     INTEGER NOT NULL UNIQUE,
    project_id  INTEGER,
    art         TEXT    NOT NULL DEFAULT '',
    daten       TEXT    NOT NULL DEFAULT '{}',
    zeit        TEXT    NOT NULL DEFAULT '',
    erledigt    TEXT    NOT NULL DEFAULT '',
    created     TEXT    NOT NULL DEFAULT ''
);
