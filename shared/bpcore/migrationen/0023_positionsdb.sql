CREATE TABLE pdb_meta(
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL DEFAULT '');

-- Verrechnungslohn je Gewerk (€/h netto inkl. Zuschläge) – in der Verwaltung anpassbar
CREATE TABLE pdb_lohn(
  gewerk TEXT PRIMARY KEY,
  name TEXT NOT NULL DEFAULT '',
  verrechnungslohn REAL NOT NULL DEFAULT 0,
  stand TEXT NOT NULL DEFAULT '');

CREATE TABLE pdb_leistungsbereich(
  nr TEXT PRIMARY KEY,                        -- z. B. '012'
  name TEXT NOT NULL DEFAULT '',              -- z. B. 'Mauerarbeiten'
  atv TEXT NOT NULL DEFAULT '',               -- VOB/C, z. B. 'DIN 18330'
  gewerk TEXT NOT NULL DEFAULT '',            -- Standard-Gewerk für den Verrechnungslohn
  sort INTEGER NOT NULL DEFAULT 0);

CREATE TABLE pdb_gruppe(
  nr TEXT PRIMARY KEY,                        -- z. B. '012.01'
  lb_nr TEXT NOT NULL REFERENCES pdb_leistungsbereich(nr) ON DELETE CASCADE,
  name TEXT NOT NULL DEFAULT '');

-- Grundtext (gemeinsamer Langtext-Anfang mehrerer Positionen), wie in StLB/ÖNORM: Langtext = Grundtext + Folgetext
CREATE TABLE pdb_grundtext(
  id TEXT PRIMARY KEY,                        -- z. B. '012.02.003.01'
  text TEXT NOT NULL DEFAULT '');
CREATE INDEX pdb_grundtext_suche ON pdb_grundtext USING gin (to_tsvector('german', text));

CREATE TABLE pdb_position(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  katalog TEXT NOT NULL DEFAULT 'eigen' REFERENCES pdb_katalog(key) ON DELETE CASCADE,
  code TEXT NOT NULL,                  -- z. B. '012.02.003.01004' (LB.Gruppe.Grundposition.Variante+Ausführung)
  grund_id TEXT REFERENCES pdb_grundtext(id) ON DELETE SET NULL,
  lb_nr TEXT NOT NULL DEFAULT '',             -- Leistungsbereich (bei Importen aus der Gliederung bzw. leer)
  gruppe TEXT NOT NULL DEFAULT '',
  titel TEXT NOT NULL DEFAULT '',             -- Gliederung bei importierten Katalogen, z. B. '012 Mauerarbeiten › Außenwände'
  kurz TEXT NOT NULL DEFAULT '',
  lang TEXT NOT NULL DEFAULT '',              -- Folgetext (bei eigenen Positionen ohne Grundtext: ganzer Langtext)
  einheit TEXT NOT NULL DEFAULT '',
  kg TEXT NOT NULL DEFAULT '',                -- DIN 276, 3-stellig
  gewerk TEXT NOT NULL DEFAULT '',            -- Schlüssel in pdb_lohn
  h REAL NOT NULL DEFAULT 0,                  -- Zeitansatz h je Einheit
  stoff REAL NOT NULL DEFAULT 0,              -- Stoffkosten €/Einheit (netto, ohne Zuschlag)
  geraet REAL NOT NULL DEFAULT 0,             -- Geräte-/Fremdkosten €/Einheit
  ep_von REAL, ep_mittel REAL, ep_bis REAL,   -- Einheitspreis netto zum Preisstand
  genauigkeit TEXT NOT NULL DEFAULT 'B',      -- A | B | C (siehe pdb_meta 'genauigkeit')
  tags TEXT NOT NULL DEFAULT '',              -- kommagetrennt, z. B. 'neubau,altbau'
  hinweis TEXT NOT NULL DEFAULT '',           -- Abrechnung, Nebenleistungen, Hinweise für den Planer
  quelle TEXT NOT NULL DEFAULT 'eigen',       -- katalog | import | eigen
  preisstand TEXT NOT NULL DEFAULT '',        -- 'JJJJ-MM'
  aktiv INTEGER NOT NULL DEFAULT 1,
  favorit INTEGER NOT NULL DEFAULT 0,
  created TEXT, updated TEXT, updated_by TEXT NOT NULL DEFAULT '');
CREATE UNIQUE INDEX pdb_position_code ON pdb_position(katalog, code);
CREATE INDEX pdb_position_lb ON pdb_position(katalog, lb_nr, code);
CREATE INDEX pdb_position_kg ON pdb_position(kg);
CREATE INDEX pdb_position_grund ON pdb_position(grund_id);
CREATE INDEX pdb_position_suche ON pdb_position USING gin (to_tsvector('german', kurz || ' ' || lang));

-- eigene Erfahrungspreise aus Vergaben (z. B. aus der AVA übernommene Auftragspreise) je Position
CREATE TABLE pdb_preis(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  position_id INTEGER NOT NULL REFERENCES pdb_position(id) ON DELETE CASCADE,
  ep REAL NOT NULL,
  datum TEXT NOT NULL DEFAULT '',
  project_id INTEGER REFERENCES projects(id) ON DELETE SET NULL,
  firma TEXT NOT NULL DEFAULT '',
  menge REAL,
  notiz TEXT NOT NULL DEFAULT '',
  created TEXT, user_name TEXT NOT NULL DEFAULT '');
CREATE INDEX pdb_preis_pos ON pdb_preis(position_id, datum);

-- Regional-/Projektfaktoren (z. B. Ruhrgebiet 1,00; Großstadt 1,08) – vom Büro gepflegt
CREATE TABLE pdb_faktor(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  faktor REAL NOT NULL DEFAULT 1,
  notiz TEXT NOT NULL DEFAULT '');
