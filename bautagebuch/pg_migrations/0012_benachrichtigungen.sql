-- Bauplattform: Benachrichtigungsverlauf je Kontakt.
-- Eine Zeile je Empfänger und Sendung (Planversand, Mängelrüge, Terminrüge …). Auch Sendungen an Adressen,
-- zu denen (noch) kein Kontakt existiert, werden protokolliert – sie erscheinen beim Kontakt, sobald er mit
-- dieser E-Mail-Adresse angelegt ist.
CREATE TABLE benachrichtigungen(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts TEXT NOT NULL,
  contact_id INTEGER REFERENCES contacts(id) ON DELETE SET NULL,
  email TEXT NOT NULL DEFAULT '',
  name TEXT NOT NULL DEFAULT '',
  art TEXT NOT NULL DEFAULT '',            -- planversand | maengelruege | terminruege | …
  weg TEXT NOT NULL DEFAULT 'mail',        -- mail | weiterleiten (an mich zum Weiterleiten) | pdf (selbst zugestellt)
  project_id INTEGER REFERENCES projects(id) ON DELETE SET NULL,
  projekt TEXT NOT NULL DEFAULT '',
  betreff TEXT NOT NULL DEFAULT '',
  inhalt TEXT NOT NULL DEFAULT '',         -- kurz: welche Pläne / Mängel
  von TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'gesendet', -- gesendet | fehler
  fehler TEXT NOT NULL DEFAULT '',
  link TEXT NOT NULL DEFAULT '');          -- app:fragment zum Öffnen der Stelle
CREATE INDEX benachrichtigungen_kontakt ON benachrichtigungen(contact_id, id);
CREATE INDEX benachrichtigungen_email ON benachrichtigungen(lower(email), id);
