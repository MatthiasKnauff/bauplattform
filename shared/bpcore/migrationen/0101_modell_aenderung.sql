-- Änderungen an den Bauteilen des Gebäudemodells (GO 20.11.2026, Mock „Gebäudemodell – neue Seite Bauteile“): je Zeile und Feld vorher → nachher,
-- wer, wann, mit welcher App. Grundlage für die Färbung „Änderungen“ und den Zeitschieber im Gebäudemodell (bpcore/modell_aenderung.py).
-- art: bauteil | plan (mit einem neuen Planstand) | raum | assistent
CREATE TABLE IF NOT EXISTS pm_aenderung (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    zeile       TEXT    NOT NULL DEFAULT '',
    ids         TEXT    NOT NULL DEFAULT '[]',
    art         TEXT    NOT NULL DEFAULT 'bauteil',
    feld        TEXT    NOT NULL DEFAULT '',
    vorher      TEXT    NOT NULL DEFAULT '',
    nachher     TEXT    NOT NULL DEFAULT '',
    text        TEXT    NOT NULL DEFAULT '',
    wann        TEXT    NOT NULL DEFAULT '',
    wer         TEXT    NOT NULL DEFAULT '',
    app         TEXT    NOT NULL DEFAULT '',
    zurueck     INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS pm_aenderung_projekt ON pm_aenderung(project_id, wann);
