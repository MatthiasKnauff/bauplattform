-- Bauplattform: Versionierung aller Einstellungen und Stammdaten (siehe shared/bpcore/versionen.py).
-- Jede Speicherung legt einen Stand an; „aenderungen“ beschreibt in Worten, was sich gegenüber dem vorigen Stand geändert hat.
CREATE TABLE versionen(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bereich TEXT NOT NULL,                     -- z. B. einst:bt, gs:library, kontakt:12, konto:3
  daten TEXT NOT NULL,                       -- vollständiger Stand (JSON, Kennwörter nur als Prüfsumme)
  aenderungen TEXT NOT NULL DEFAULT '[]',    -- JSON-Liste mit Änderungen in Worten
  wer TEXT NOT NULL DEFAULT '',
  wann TEXT NOT NULL,
  art TEXT NOT NULL DEFAULT 'auto',          -- auto | benannt | wiederhergestellt | ausgang
  name TEXT NOT NULL DEFAULT '',
  groesse INTEGER NOT NULL DEFAULT 0);
CREATE INDEX versionen_bereich ON versionen(bereich, id);
CREATE INDEX versionen_wann ON versionen(wann);
