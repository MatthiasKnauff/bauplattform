-- Bauplattform: Planversandliste der App „Planstand & Versand“.
-- Eine Zeile je Versand (an eine Firma oder an mich zum Weiterleiten) mit den versendeten Plänen.
CREATE TABLE planversand(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  datum TEXT NOT NULL,
  absender TEXT NOT NULL DEFAULT '',
  art TEXT NOT NULL DEFAULT 'direkt',        -- direkt (an die Empfänger) | mich (an mich zum Weiterleiten)
  empfaenger TEXT NOT NULL DEFAULT '[]',     -- JSON [{name, email}]
  plaene TEXT NOT NULL DEFAULT '[]',         -- JSON [{name, pfad, nr, index, titel, kennung, cad:[Dateinamen]}]
  betreff TEXT NOT NULL DEFAULT '');
CREATE INDEX planversand_projekt ON planversand(project_id, id);
