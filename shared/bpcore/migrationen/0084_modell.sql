-- Projektmodell über allen Apps (besprochen am 15.11.2026, Entwurf „Planung – Verknüpfungen“; Programm: bpcore/modell.py)
-- pm_modell   je Projekt EIN Modell (Gebäude, Geschosse, Einheiten, Räume, Bauteile grob, KI an/aus) – rev schützt vor gegenseitigem Überschreiben
-- pm_stand    nummerierte Stände des Modells mit freiem Kommentar; anlass „hand“ oder „ausgang:<app>“ (etwas hat das Haus verlassen)
-- pm_link     je App höchstens EINE Linie zum Modell – nur gespeichert, wenn sie vom Standard abweicht:
--             richtung beide | zur_app | zum_modell · uebernahme uebernahme | auto · zustand lebendig | fest | getrennt;
--             fest: stand_ref/stand_name = der eingefrorene Stand der App, modell_stand = der Modellstand, zu dem er gehört
-- pm_verlauf  eigenes Rückgängig der Verknüpfungen: je Schritt die Linien vorher/nachher; zurueck 0 = gilt, 1 = zurückgenommen (wiederholbar), 2 = verworfen
-- pm_hinweis  Vorschläge, die an einer Linie auf eine Entscheidung warten (rote Zahl): quelle regel | ki, status offen | uebernommen | abgelehnt | spaeter
CREATE TABLE IF NOT EXISTS pm_modell (
    project_id  INTEGER PRIMARY KEY REFERENCES projects(id) ON DELETE CASCADE,
    data        TEXT    NOT NULL DEFAULT '{}',
    rev         INTEGER NOT NULL DEFAULT 1,
    erstellt    TEXT    NOT NULL DEFAULT '',
    geaendert   TEXT    NOT NULL DEFAULT '',
    von         TEXT    NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS pm_stand (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    nr          INTEGER NOT NULL,
    kommentar   TEXT    NOT NULL DEFAULT '',
    anlass      TEXT    NOT NULL DEFAULT 'hand',
    daten       TEXT    NOT NULL DEFAULT '{}',
    links       TEXT    NOT NULL DEFAULT '[]',
    wann        TEXT    NOT NULL DEFAULT '',
    wer         TEXT    NOT NULL DEFAULT '',
    UNIQUE (project_id, nr)
);
CREATE TABLE IF NOT EXISTS pm_link (
    project_id   INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    app          TEXT    NOT NULL,
    richtung     TEXT    NOT NULL DEFAULT 'beide',
    uebernahme   TEXT    NOT NULL DEFAULT 'uebernahme',
    zustand      TEXT    NOT NULL DEFAULT 'lebendig',
    stand_ref    TEXT    NOT NULL DEFAULT '',
    stand_name   TEXT    NOT NULL DEFAULT '',
    modell_stand INTEGER,
    geaendert    TEXT    NOT NULL DEFAULT '',
    von          TEXT    NOT NULL DEFAULT '',
    PRIMARY KEY (project_id, app)
);
CREATE TABLE IF NOT EXISTS pm_verlauf (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    text        TEXT    NOT NULL DEFAULT '',
    vorher      TEXT    NOT NULL DEFAULT '{}',
    nachher     TEXT    NOT NULL DEFAULT '{}',
    zurueck     INTEGER NOT NULL DEFAULT 0,
    wann        TEXT    NOT NULL DEFAULT '',
    wer         TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS pm_verlauf_projekt ON pm_verlauf(project_id, id);
CREATE TABLE IF NOT EXISTS pm_hinweis (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    app          TEXT    NOT NULL,
    titel        TEXT    NOT NULL DEFAULT '',
    daten        TEXT    NOT NULL DEFAULT '{}',
    quelle       TEXT    NOT NULL DEFAULT 'regel',
    status       TEXT    NOT NULL DEFAULT 'offen',
    wann         TEXT    NOT NULL DEFAULT '',
    wer          TEXT    NOT NULL DEFAULT '',
    erledigt     TEXT    NOT NULL DEFAULT '',
    erledigt_von TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS pm_hinweis_projekt ON pm_hinweis(project_id, status);
