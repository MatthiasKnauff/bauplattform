-- Kommunikation: Vorgänge von der Baustelle (Telefon-, Gesprächs-, Aktennotiz, Anordnung, Behinderungsanzeige, Bedenkenanmeldung,
-- Begehung) – nur festgehalten oder an Beteiligte geschickt; Fotos und Dateien dazu. Gesendete Nachrichten stehen wie bisher in
-- benachrichtigungen (art 'nachricht' bzw. 'vorgang'), mit Verweis auf den Vorgang.
CREATE TABLE IF NOT EXISTS kom_vorgang(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER REFERENCES projects(id) ON DELETE SET NULL,
  art TEXT NOT NULL DEFAULT 'notiz',
  titel TEXT NOT NULL DEFAULT '',
  text TEXT NOT NULL DEFAULT '',
  beteiligte TEXT NOT NULL DEFAULT '',          -- frei: wer war dabei / am Telefon
  zeit TEXT NOT NULL DEFAULT '',                -- JJJJ-MM-TTTHH:MM (wann es war)
  ort TEXT NOT NULL DEFAULT '',
  frist TEXT NOT NULL DEFAULT '',
  todo_id INTEGER REFERENCES todo(id) ON DELETE SET NULL,
  an TEXT NOT NULL DEFAULT '[]',                -- Empfänger (JSON [{email, name, contact_id}]), leer = nur festgehalten
  gesendet TEXT NOT NULL DEFAULT '',            -- wann verschickt
  erstellt TEXT NOT NULL DEFAULT '', erstellt_von INTEGER, erstellt_name TEXT NOT NULL DEFAULT '');
CREATE INDEX IF NOT EXISTS idx_kom_vorgang_proj ON kom_vorgang(project_id, zeit);

CREATE TABLE IF NOT EXISTS kom_datei(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vorgang_id INTEGER REFERENCES kom_vorgang(id) ON DELETE CASCADE,
  benachrichtigung_id INTEGER,                  -- Anhang einer Nachricht (benachrichtigungen.id der ersten Zeile)
  name TEXT NOT NULL DEFAULT '',
  mime TEXT NOT NULL DEFAULT 'application/octet-stream',
  groesse INTEGER NOT NULL DEFAULT 0,
  data BYTEA,
  erstellt TEXT NOT NULL DEFAULT '', erstellt_name TEXT NOT NULL DEFAULT '');
CREATE INDEX IF NOT EXISTS idx_kom_datei_v ON kom_datei(vorgang_id);
CREATE INDEX IF NOT EXISTS idx_kom_datei_b ON kom_datei(benachrichtigung_id);
