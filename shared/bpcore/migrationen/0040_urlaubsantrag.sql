-- Zeiten: Urlaubsanträge. Mitarbeiter:innen beantragen Urlaub, Frei/Ausgleich oder Fortbildung für einen Zeitraum;
-- Administratoren genehmigen oder lehnen ab. Erst die Genehmigung trägt die Abwesenheit in zeit_tag ein.
-- status: offen, genehmigt, abgelehnt, zurueckgezogen; tage = Arbeitstage im Zeitraum (halber Urlaubstag = 0,5)
CREATE TABLE IF NOT EXISTS zeit_antrag (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    von             TEXT    NOT NULL,
    bis             TEXT    NOT NULL,
    art             TEXT    NOT NULL DEFAULT 'urlaub',
    tage            REAL    NOT NULL DEFAULT 0,
    notiz           TEXT    NOT NULL DEFAULT '',
    vertretung      TEXT    NOT NULL DEFAULT '',
    status          TEXT    NOT NULL DEFAULT 'offen',
    antwort         TEXT    NOT NULL DEFAULT '',
    entschieden_von TEXT    NOT NULL DEFAULT '',
    entschieden     TEXT    NOT NULL DEFAULT '',
    erstellt        TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS idx_zeit_antrag_user ON zeit_antrag(user_id, status);
