-- Wärmeschutz: Baustoffdatenbank. Eingebaute Baustoffe (herkunft 'eingebaut') kommen aus bpcore/ws_baustoffe.json und werden beim Start
-- der App abgeglichen (neue angelegt, Werte nachgeführt); eigene (herkunft 'eigen') legt das Büro an. Bauteile und der Bauteilkatalog
-- verweisen über den Schlüssel – ändert sich ein Wert, rechnen alle Bauteile damit.
CREATE TABLE IF NOT EXISTS ws_baustoff (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schluessel  TEXT    NOT NULL UNIQUE,
    kat         TEXT    NOT NULL DEFAULT 'Sonstiges',
    name        TEXT    NOT NULL DEFAULT '',
    hersteller  TEXT    NOT NULL DEFAULT '',
    lambda      DOUBLE PRECISION,
    rho         DOUBLE PRECISION,
    mu          DOUBLE PRECISION,
    mu2         DOUBLE PRECISION,
    sd          DOUBLE PRECISION,
    c           DOUBLE PRECISION,
    farbe       TEXT    NOT NULL DEFAULT '#dcdcdc',
    art         TEXT    NOT NULL DEFAULT '',      -- '' | luft | belueftet
    holz        TEXT    NOT NULL DEFAULT '',      -- '' | vollholz | werkstoff
    quelle      TEXT    NOT NULL DEFAULT '',
    stand       TEXT    NOT NULL DEFAULT '',
    url         TEXT    NOT NULL DEFAULT '',
    hinweis     TEXT    NOT NULL DEFAULT '',
    herkunft    TEXT    NOT NULL DEFAULT 'eigen',
    aktiv       BOOLEAN NOT NULL DEFAULT TRUE,
    geaendert   TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    von         TEXT    NOT NULL DEFAULT ''
);
