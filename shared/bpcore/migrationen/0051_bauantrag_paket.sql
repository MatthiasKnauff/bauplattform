-- Bauantrag: eigene Unterlagen je Antrag (PDF, Scan, Foto → PDF) und die Platzierung von Werten auf Vordrucken ohne Formularfelder.
-- Welche Vordrucke ein Antrag nutzt und in welcher Reihenfolge, steht in bauantrag.daten unter „_paket“ ({an: [...], aus: [...], reihe: [...]}).
-- bauantrag_platzierung je Datei-Inhalt (sha256): dieselbe Datei füllt sich beim nächsten Antrag von selbst; neue Fassung = neu platzieren.
CREATE TABLE IF NOT EXISTS bauantrag_unterlage (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    antrag_id INTEGER NOT NULL REFERENCES bauantrag(id) ON DELETE CASCADE,
    name      TEXT    NOT NULL DEFAULT '',
    daten     BYTEA,
    sha256    TEXT    NOT NULL DEFAULT '',
    art       TEXT    NOT NULL DEFAULT 'beilegen',
    erstellt  TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    von       TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_bauantrag_unterlage_antrag ON bauantrag_unterlage(antrag_id);
CREATE TABLE IF NOT EXISTS bauantrag_platzierung (
    sha256    TEXT PRIMARY KEY,
    felder    TEXT NOT NULL DEFAULT '[]',
    geaendert TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    von       TEXT NOT NULL DEFAULT ''
);
