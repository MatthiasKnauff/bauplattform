-- Bauplattform AVA: Versionen je Projekt (Startversion, Bauherrenwünsche eingearbeitet …) – wie Dateien:
-- jede Version hat ihre eigenen LVs (mit Angeboten, Aufmaß, Rechnungen, Fotos). Genau eine Version je Projekt ist
-- „aktiv“: die zuletzt geöffnete. Nur ihre LVs zählen für To-dos, Budget und Suche in den anderen Apps.
CREATE TABLE ava_version(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL DEFAULT '',
  aktiv INTEGER NOT NULL DEFAULT 0,
  archived INTEGER NOT NULL DEFAULT 0,
  von INTEGER,                                -- aus welcher Version kopiert
  created TEXT, updated TEXT, updated_by TEXT NOT NULL DEFAULT '');
CREATE INDEX ava_version_projekt ON ava_version(project_id, id);

ALTER TABLE ava_lv ADD COLUMN version_id INTEGER REFERENCES ava_version(id) ON DELETE CASCADE;
CREATE INDEX ava_lv_version ON ava_lv(version_id);

-- bestehende LVs: je Projekt eine „Startversion“
INSERT INTO ava_version(project_id, name, aktiv, created, updated)
  SELECT DISTINCT project_id, 'Startversion', 1, to_char(now(), 'YYYY-MM-DD"T"HH24:MI:SS'), to_char(now(), 'YYYY-MM-DD"T"HH24:MI:SS')
  FROM ava_lv WHERE project_id IS NOT NULL;
UPDATE ava_lv SET version_id = (SELECT v.id FROM ava_version v WHERE v.project_id = ava_lv.project_id) WHERE project_id IS NOT NULL;

-- neue LVs landen automatisch in der aktiven Version ihres Projekts (fehlt sie, entsteht die „Startversion“)
CREATE FUNCTION ava_lv_version() RETURNS trigger AS $$
DECLARE v INTEGER;
BEGIN
  IF NEW.version_id IS NULL AND NEW.project_id IS NOT NULL THEN
    SELECT id INTO v FROM ava_version WHERE project_id = NEW.project_id AND aktiv = 1 ORDER BY id DESC LIMIT 1;
    IF v IS NULL THEN
      INSERT INTO ava_version(project_id, name, aktiv, created, updated, updated_by)
        VALUES (NEW.project_id, 'Startversion', 1, NEW.created, NEW.created, NEW.updated_by) RETURNING id INTO v;
    END IF;
    NEW.version_id := v;
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
CREATE TRIGGER ava_lv_version BEFORE INSERT ON ava_lv FOR EACH ROW EXECUTE FUNCTION ava_lv_version();
