-- Zeiterfassung (App „Zeiten“): Arbeitszeit (Kommen/Gehen, Pause, Urlaub/Krank) und Projektzeiten je Leistungsphase.
-- Vorschläge entstehen aus der Arbeit in der Plattform (zeit_puls: je Benutzer und Minute die geöffnete App und das Projekt)
-- und aus „vor Ort“ (Kurzbefehl, bpcore/vorort.py). Zählen tut nur, was der Benutzer bestätigt (zeit_eintrag, zeit_tag).

-- Puls: höchstens eine Zeile je Benutzer und Minute (Ortszeit, „JJJJ-MM-TT HH:MM“); wird nach 60 Tagen gelöscht
CREATE TABLE IF NOT EXISTS zeit_puls(
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  ts TEXT NOT NULL,
  app TEXT NOT NULL DEFAULT '', bereich TEXT NOT NULL DEFAULT '',
  project_id INTEGER,
  PRIMARY KEY(user_id, ts));

-- bestätigte bzw. von Hand erfasste Zeiten (art: lph1 … lph9, fahrt, buero, sonst)
CREATE TABLE IF NOT EXISTS zeit_eintrag(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  tag TEXT NOT NULL, von TEXT NOT NULL, bis TEXT NOT NULL,
  project_id INTEGER REFERENCES projects(id) ON DELETE SET NULL,
  art TEXT NOT NULL DEFAULT '', notiz TEXT NOT NULL DEFAULT '', quelle TEXT NOT NULL DEFAULT 'hand',
  created TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  updated TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'));
CREATE INDEX IF NOT EXISTS idx_zeit_eintrag_tag ON zeit_eintrag(user_id, tag);
CREATE INDEX IF NOT EXISTS idx_zeit_eintrag_proj ON zeit_eintrag(project_id);

-- je Benutzer und Tag: Kommen/Gehen/Pause (leer = Vorschlag), Abwesenheit, bestätigt, verworfene Vorschläge
CREATE TABLE IF NOT EXISTS zeit_tag(
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  tag TEXT NOT NULL,
  kommen TEXT NOT NULL DEFAULT '', gehen TEXT NOT NULL DEFAULT '', pause INTEGER,
  abw TEXT NOT NULL DEFAULT '', notiz TEXT NOT NULL DEFAULT '',
  bestaetigt TEXT NOT NULL DEFAULT '', ignor TEXT NOT NULL DEFAULT '[]',
  PRIMARY KEY(user_id, tag));

-- je Mitarbeiter:in: Sollzeit, Arbeitstage (0 = Montag), Urlaubstage im Jahr, Stundensatz, Saldo zu Beginn
CREATE TABLE IF NOT EXISTS zeit_person(
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  soll_woche REAL NOT NULL DEFAULT 40, tage TEXT NOT NULL DEFAULT '01234', urlaub REAL NOT NULL DEFAULT 30,
  satz REAL, saldo_start REAL NOT NULL DEFAULT 0, ab TEXT NOT NULL DEFAULT '', aus INTEGER NOT NULL DEFAULT 0);

-- je Projekt: Honorar, Soll-Stunden je Leistungsphase (JSON), Fahrzeit je Richtung in Minuten
CREATE TABLE IF NOT EXISTS zeit_projekt(
  project_id INTEGER PRIMARY KEY REFERENCES projects(id) ON DELETE CASCADE,
  honorar REAL, soll TEXT NOT NULL DEFAULT '{}', fahrt INTEGER);

-- laufende Stoppuhr je Benutzer
CREATE TABLE IF NOT EXISTS zeit_lauf(
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  start TEXT NOT NULL, project_id INTEGER, art TEXT NOT NULL DEFAULT '', notiz TEXT NOT NULL DEFAULT '');
