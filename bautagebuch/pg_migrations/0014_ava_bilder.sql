-- Bauplattform AVA: Fotos/Skizzen zu Positionen (erscheinen unter dem Langtext und im LV-Ausdruck).
CREATE TABLE ava_bild(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lv_id INTEGER NOT NULL REFERENCES ava_lv(id) ON DELETE CASCADE,
  pos_id TEXT NOT NULL DEFAULT '',            -- id der Position in ava_lv.data.items
  name TEXT NOT NULL DEFAULT '',
  w INTEGER NOT NULL DEFAULT 0, h INTEGER NOT NULL DEFAULT 0,
  data BYTEA,                                 -- JPEG, längste Seite höchstens 1600 px
  klein BYTEA,                                -- Vorschau, höchstens 360 px
  created TEXT NOT NULL DEFAULT '', user_name TEXT NOT NULL DEFAULT '');
CREATE INDEX ava_bild_lv ON ava_bild(lv_id, pos_id, id);
