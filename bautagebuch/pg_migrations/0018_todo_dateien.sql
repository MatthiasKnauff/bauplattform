-- Bauplattform: Anhänge und Fotos zu den Aufgaben der To-do-Liste.
CREATE TABLE todo_datei(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  todo_id INTEGER NOT NULL REFERENCES todo(id) ON DELETE CASCADE,
  name TEXT NOT NULL DEFAULT '',
  mime TEXT NOT NULL DEFAULT 'application/octet-stream',
  groesse INTEGER NOT NULL DEFAULT 0,
  data BYTEA,
  erstellt TEXT NOT NULL DEFAULT '', erstellt_name TEXT NOT NULL DEFAULT '');
CREATE INDEX todo_datei_todo ON todo_datei(todo_id);
