-- PostgreSQL-Grundschema des Bautagebuchs (Stand der früheren SQLite-Migrationen 0001–0019).
-- Datumsfelder bleiben Text („JJJJ-MM-TT“ bzw. „JJJJ-MM-TT HH:MM:SS“), damit die App unverändert damit rechnet.
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE projects(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, created TEXT DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  extra TEXT NOT NULL DEFAULT '{}', updated TEXT,
  client TEXT NOT NULL DEFAULT '', street TEXT NOT NULL DEFAULT '', zip TEXT NOT NULL DEFAULT '', city TEXT NOT NULL DEFAULT '',
  lat DOUBLE PRECISION, lon DOUBLE PRECISION, folder TEXT NOT NULL DEFAULT '',
  archived INTEGER NOT NULL DEFAULT 0,
  leaders TEXT NOT NULL DEFAULT '[]');   -- JSON-Liste von Benutzer-IDs; leer = alle sehen das Projekt

CREATE TABLE contacts(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name CITEXT NOT NULL UNIQUE,
  trade TEXT NOT NULL DEFAULT '', contact_person TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '', mobile TEXT NOT NULL DEFAULT '', email TEXT NOT NULL DEFAULT '',
  street TEXT NOT NULL DEFAULT '', zip TEXT NOT NULL DEFAULT '', city TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '', extra TEXT NOT NULL DEFAULT '{}', created TEXT, updated TEXT);

CREATE TABLE users(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name CITEXT NOT NULL UNIQUE,
  email TEXT NOT NULL DEFAULT '', pass_hash TEXT NOT NULL DEFAULT '',
  is_admin INTEGER NOT NULL DEFAULT 0,
  must_change INTEGER NOT NULL DEFAULT 0,
  extra TEXT NOT NULL DEFAULT '{}',
  created TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  updated TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  accent TEXT NOT NULL DEFAULT '');

CREATE TABLE password_resets(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE, expires BIGINT NOT NULL,
  created TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'));

CREATE TABLE reports(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  number INTEGER, date TEXT, weather TEXT DEFAULT '', temp TEXT DEFAULT '', humidity TEXT DEFAULT '', wind TEXT DEFAULT '',
  plz TEXT DEFAULT '', extra TEXT NOT NULL DEFAULT '{}', created TEXT, updated TEXT,
  time TEXT NOT NULL DEFAULT '', site_manager TEXT NOT NULL DEFAULT '', precip TEXT NOT NULL DEFAULT '',
  chk_tidy INTEGER NOT NULL DEFAULT 0, chk_measure INTEGER NOT NULL DEFAULT 0, chk_photos INTEGER NOT NULL DEFAULT 0, chk_firms INTEGER NOT NULL DEFAULT 0);
CREATE INDEX idx_reports_project ON reports(project_id, date);

CREATE TABLE items(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id INTEGER NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  kind TEXT, text TEXT, done INTEGER DEFAULT 0, extra TEXT NOT NULL DEFAULT '{}', created TEXT, updated TEXT,
  contact_id INTEGER REFERENCES contacts(id) ON DELETE SET NULL,
  activity TEXT NOT NULL DEFAULT '', headcount INTEGER,
  due TEXT NOT NULL DEFAULT '', remind_user INTEGER, reminded TEXT NOT NULL DEFAULT '',
  due_time TEXT NOT NULL DEFAULT '09:00', company TEXT NOT NULL DEFAULT '');
CREATE INDEX idx_items_report ON items(report_id, kind);
CREATE INDEX idx_items_contact ON items(contact_id);
CREATE INDEX idx_items_due ON items(due) WHERE due != '';

CREATE TABLE images(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id INTEGER NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  file TEXT, extra TEXT NOT NULL DEFAULT '{}', caption TEXT DEFAULT '', created TEXT,
  item_id INTEGER REFERENCES items(id) ON DELETE SET NULL, sent_remote TEXT NOT NULL DEFAULT '');
CREATE INDEX idx_images_report ON images(report_id);
CREATE INDEX idx_images_item ON images(item_id);

