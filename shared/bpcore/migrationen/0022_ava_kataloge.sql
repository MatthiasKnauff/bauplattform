-- Bauplattform AVA: mehrere Kataloge (z. B. sirAdos Positionen und sirAdos Elemente) statt nur einem.
CREATE TABLE ava_kataloge(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL DEFAULT '',              -- Anzeige, z. B. „sirAdos Positionen 07/2019“ (umbenennbar)
  quelle TEXT NOT NULL DEFAULT '', stand TEXT NOT NULL DEFAULT '',
  art TEXT NOT NULL DEFAULT 'positionen',     -- positionen | elemente
  datei TEXT NOT NULL DEFAULT '',             -- dieselbe Datei noch einmal eingelesen: ersetzt den Katalog
  n_pos INTEGER NOT NULL DEFAULT 0, n_gewerke INTEGER NOT NULL DEFAULT 0,
  importiert TEXT NOT NULL DEFAULT '', von TEXT NOT NULL DEFAULT '');
ALTER TABLE ava_katalog ADD COLUMN katalog_id INTEGER REFERENCES ava_kataloge(id) ON DELETE CASCADE;
CREATE INDEX ava_katalog_kat ON ava_katalog(katalog_id, gewerk, nr);

-- bisheriger (einziger) Katalog: Angaben aus bp_store übernehmen
INSERT INTO ava_kataloge(name, quelle, stand, art, datei, n_pos, n_gewerke, importiert, von)
  SELECT trim(coalesce(d->>'quelle', 'Katalog') || ' Positionen' || CASE WHEN length(coalesce(d->>'stand', '')) >= 7 THEN ' ' || substr(d->>'stand', 6, 2) || '/' || substr(d->>'stand', 1, 4) ELSE '' END),
         coalesce(d->>'quelle', ''), coalesce(d->>'stand', ''), 'positionen', coalesce(d->>'datei', ''),
         coalesce((d->>'n_pos')::int, 0), coalesce((d->>'n_gewerke')::int, 0), coalesce(d->>'importiert', ''), coalesce(d->>'von', '')
  FROM (SELECT data::json AS d FROM bp_store WHERE key='ava:katalog') x;
UPDATE ava_katalog SET katalog_id=(SELECT max(id) FROM ava_kataloge);
DELETE FROM ava_katalog WHERE katalog_id IS NULL;
DELETE FROM bp_store WHERE key='ava:katalog';
