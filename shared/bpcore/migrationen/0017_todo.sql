-- Bauplattform: To-do-Liste der Startseite (manuelle Aufgaben).
-- Automatische Aufgaben (Analysen) werden nicht gespeichert, sondern bei jedem Abruf aus den Daten der Apps berechnet;
-- ihre Einstellungen und was jemand zurückgestellt/ausgeblendet hat, liegen in bp_store („todo:regeln“, „todo:zustand:<uid>“).
CREATE TABLE todo(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titel TEXT NOT NULL DEFAULT '',
  notiz TEXT NOT NULL DEFAULT '',
  project_id INTEGER REFERENCES projects(id) ON DELETE SET NULL,
  faellig TEXT NOT NULL DEFAULT '',          -- JJJJ-MM-TT oder leer
  prio INTEGER NOT NULL DEFAULT 0,           -- 0 normal, 1 wichtig
  personen TEXT NOT NULL DEFAULT '[]',       -- Benutzer-IDs (JSON), die die Aufgabe sehen und erledigen können
  mail INTEGER NOT NULL DEFAULT 0,           -- Beteiligte per Mail benachrichtigen
  status TEXT NOT NULL DEFAULT 'offen',      -- offen | erledigt
  erstellt TEXT NOT NULL DEFAULT '', erstellt_von INTEGER, erstellt_name TEXT NOT NULL DEFAULT '',
  erledigt TEXT NOT NULL DEFAULT '', erledigt_name TEXT NOT NULL DEFAULT '',
  geaendert TEXT NOT NULL DEFAULT '');
CREATE INDEX todo_status ON todo(status, faellig);
