-- Honorar: Abschlags- und Schlussrechnungen je Honorarauftrag (§ 15 HOAI).
-- art: abschlag | schluss; status: entwurf | gestellt | bezahlt | storniert. Je Auftrag höchstens ein Entwurf (immer die letzte Rechnung).
-- stand: JSON der Berechnung (kumulierte Leistung je LPh, Umbau, Nebenkosten, bisherige Rechnungen) – beim Stellen eingefroren,
-- damit Rechnung und Erläuterung später genau so wieder gedruckt werden. nr frei änderbar, Vorschlag aus jahr/lfd.
CREATE TABLE IF NOT EXISTS honorar_rechnung (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auftrag_id  INTEGER NOT NULL REFERENCES honorar_auftrag(id) ON DELETE CASCADE,
    art         TEXT    NOT NULL DEFAULT 'abschlag',
    nr          TEXT    NOT NULL DEFAULT '',
    jahr        INTEGER NOT NULL DEFAULT 0,
    lfd         INTEGER NOT NULL DEFAULT 0,
    datum       TEXT    NOT NULL DEFAULT '',
    anteil      DOUBLE PRECISION,
    empfaenger  TEXT    NOT NULL DEFAULT '',
    text        TEXT    NOT NULL DEFAULT '',
    stand       TEXT    NOT NULL DEFAULT '{}',
    betrag      DOUBLE PRECISION NOT NULL DEFAULT 0,
    mwst        DOUBLE PRECISION NOT NULL DEFAULT 0,
    brutto      DOUBLE PRECISION NOT NULL DEFAULT 0,
    status      TEXT    NOT NULL DEFAULT 'entwurf',
    bezahlt_am  TEXT    NOT NULL DEFAULT '',
    bezahlt     DOUBLE PRECISION,
    erstellt    TEXT    NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
    von         TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_honorar_rechnung_auftrag ON honorar_rechnung(auftrag_id);

DO $$
BEGIN
    IF to_regprocedure('bp_aenderung_merken()') IS NOT NULL THEN
        DROP TRIGGER IF EXISTS bp_live ON honorar_rechnung;
        CREATE TRIGGER bp_live AFTER INSERT OR UPDATE OR DELETE ON honorar_rechnung FOR EACH ROW EXECUTE FUNCTION bp_aenderung_merken();
    END IF;
END $$;
