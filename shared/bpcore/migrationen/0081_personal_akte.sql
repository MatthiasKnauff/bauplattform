-- App „Personal“: vollständige Personalakte (besprochen am 14.11.2026, Mock „Personalakte“) – weitere Angaben als JSON (daten),
-- Personalstatus (personal = 0: Konto ohne Personalstatus, z. B. „admin“ oder extern – nicht in Liste, Kalender, Urlaub),
-- Fristen je Person (Ersthelfer:in, Unterweisung …) mit Erinnerung (To-do vorab). Dokumente bleiben auf dem Dateiserver.
ALTER TABLE personal_person ADD COLUMN IF NOT EXISTS daten TEXT NOT NULL DEFAULT '{}';
ALTER TABLE personal_person ADD COLUMN IF NOT EXISTS personal INTEGER NOT NULL DEFAULT 1;
CREATE TABLE IF NOT EXISTS personal_frist (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER NOT NULL,
    titel      TEXT    NOT NULL DEFAULT '',
    bis        TEXT    NOT NULL DEFAULT '',
    intervall  INTEGER NOT NULL DEFAULT 0,      -- Monate bis zur nächsten Wiederholung (0 = einmalig)
    vorab      INTEGER NOT NULL DEFAULT 30,     -- Tage vorher erinnern (Glocke)
    notiz      TEXT    NOT NULL DEFAULT '',
    geaendert  TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS personal_frist_user ON personal_frist(user_id);
