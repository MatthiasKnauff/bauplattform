-- Teilen ohne Anmeldung – ein Baustein für alle Apps (besprochen am 14.11.2026, Mock „Plan teilen“):
-- bp_teilen: alle Links zum Ansehen (Bauzeitenplan, später Pläne & Dateien und Download-Links im Versand) – mit Kontakt aus den Adressen
--            und Optionen der App (z. B. Fortschritt, nur Gewerk der Firma). art „mit“ = mitlaufend, „fest“ = Stand beim Erstellen (stand).
-- bp_teilen_vorlage: Voreinstellungen fürs Teilen – uid NULL = vom Büro (nur Verwaltung ändert), sonst eigene der Benutzer:in.
-- Die Links des Bauzeitenplans (gantt_links) ziehen einmal hierher um; die alte Tabelle bleibt unangetastet stehen.
CREATE TABLE IF NOT EXISTS bp_teilen (
    token       TEXT    PRIMARY KEY,
    app         TEXT    NOT NULL DEFAULT '',
    objekt      TEXT    NOT NULL DEFAULT '',
    project_id  INTEGER,
    contact_id  INTEGER,
    name        TEXT    NOT NULL DEFAULT '',
    art         TEXT    NOT NULL DEFAULT 'mit',
    optionen    TEXT    NOT NULL DEFAULT '{}',
    stand       TEXT,
    stand_name  TEXT    NOT NULL DEFAULT '',
    ablauf      TEXT    NOT NULL DEFAULT '',
    aktiv       INTEGER NOT NULL DEFAULT 1,
    erstellt    TEXT    NOT NULL DEFAULT '',
    von         TEXT    NOT NULL DEFAULT '',
    zuletzt     TEXT    NOT NULL DEFAULT '',
    aufrufe     INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS bp_teilen_objekt ON bp_teilen(app, objekt);
CREATE TABLE IF NOT EXISTS bp_teilen_vorlage (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app        TEXT    NOT NULL DEFAULT '',
    name       TEXT    NOT NULL DEFAULT '',
    farbe      TEXT    NOT NULL DEFAULT '',
    optionen   TEXT    NOT NULL DEFAULT '{}',
    uid        INTEGER,
    sort       INTEGER NOT NULL DEFAULT 0,
    geaendert  TEXT    NOT NULL DEFAULT '',
    von        TEXT    NOT NULL DEFAULT ''
);
INSERT INTO bp_teilen(token, app, objekt, project_id, name, art, optionen, stand, stand_name, ablauf, aktiv, erstellt, von, zuletzt, aufrufe)
SELECT l.token, 'gantt', l.gantt_id, p.project_id, l.name, l.art,
       CASE WHEN l.fortschritt = 1 THEN '{"fortschritt": true}' ELSE '{"fortschritt": false}' END,
       l.stand, l.stand_name, l.ablauf, l.aktiv, l.erstellt, l.von, COALESCE(l.zuletzt, ''), l.aufrufe
  FROM gantt_links l LEFT JOIN gantt_projects p ON p.id = l.gantt_id
ON CONFLICT (token) DO NOTHING;
