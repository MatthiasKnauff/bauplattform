-- Der Planungsassistent lernt (GO 16.11.2026, Entwurf „Gebäudemodell als Mitte“, Punkt 6, D: fürs ganze Büro, E: Vorschlag schon nach einmal)
-- Ergänzungen, die jemand in einem Projekt im Assistenten gemacht hat (eigene Leistung, Ergänzung zu einem Abschnitt), mit dem Profil des
-- Gebäudes – bei einem ähnlichen Gebäude schlägt der Assistent sie wieder vor („1× in Projekt X“). Programm: bpcore/lernen.py
CREATE TABLE IF NOT EXISTS pm_lernen (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  INTEGER NOT NULL,
    art         TEXT    NOT NULL DEFAULT '',
    abschnitt   TEXT    NOT NULL DEFAULT '',
    schluessel  TEXT    NOT NULL DEFAULT '',
    text        TEXT    NOT NULL DEFAULT '',
    daten       TEXT    NOT NULL DEFAULT '{}',
    profil      TEXT    NOT NULL DEFAULT '{}',
    wer         TEXT    NOT NULL DEFAULT '',
    wann        TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS pm_lernen_schluessel ON pm_lernen(schluessel);
CREATE INDEX IF NOT EXISTS pm_lernen_projekt ON pm_lernen(project_id);
